"""Tiny ES-module bundler for this project (no npm needed).

Turns js/main.js and everything it imports (including the vendored three.js) into one
classic script, game.bundle.js, so index.html also works when opened straight from disk.
Supports the import/export forms used in this project only.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ALIAS = {'three': ROOT / 'vendor/three.module.js'}

RE_IMPORT_NAMED = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*['\"]([^'\"]+)['\"];?", re.M | re.S)
RE_IMPORT_STAR = re.compile(r"^import\s*\*\s*as\s+(\w+)\s+from\s*['\"]([^'\"]+)['\"];?", re.M)
RE_EXPORT_DECL = re.compile(r"^export\s+(async\s+function\*?|function\*?|class|const|let|var)\s+(\w+)", re.M)
RE_EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\};?", re.M | re.S)


def resolve(spec, frm):
    if spec in ALIAS:
        return ALIAS[spec].resolve()
    if spec.startswith('.'):
        return (frm.parent / spec).resolve()
    sys.exit(f'cannot resolve {spec!r} from {frm}')


order, seen, src = [], set(), {}


def visit(path):
    if path in seen:
        return
    seen.add(path)
    text = path.read_text()
    deps = [m.group(2) for m in RE_IMPORT_NAMED.finditer(text)] + [m.group(2) for m in RE_IMPORT_STAR.finditer(text)]
    for d in deps:
        visit(resolve(d, path))
    src[path] = text
    order.append(path)


def key(p):
    return p.relative_to(ROOT).as_posix()


def transform(path):
    text = src[path]

    def named(m):
        names = []
        for part in m.group(1).split(','):
            part = part.strip()
            if not part:
                continue
            a = re.split(r'\s+as\s+', part)
            names.append(a[0] if len(a) == 1 else f'{a[0]}: {a[1]}')
        return f"const {{ {', '.join(names)} }} = __M[{key(resolve(m.group(2), path))!r}];"

    text = RE_IMPORT_NAMED.sub(named, text)
    text = RE_IMPORT_STAR.sub(lambda m: f"const {m.group(1)} = __M[{key(resolve(m.group(2), path))!r}];", text)
    exports = {}

    def decl(m):
        if m.group(1) in ('let', 'var'):
            sys.exit(f'{key(path)}: "export {m.group(1)}" is not supported (live binding)')
        exports[m.group(2)] = m.group(2)
        return f'{m.group(1)} {m.group(2)}'

    text = RE_EXPORT_DECL.sub(decl, text)

    def lst(m):
        for part in m.group(1).split(','):
            part = part.strip()
            if part:
                a = re.split(r'\s+as\s+', part)
                exports[a[-1]] = a[0]
        return ''

    text = RE_EXPORT_LIST.sub(lst, text)
    if re.search(r'^\s*(import|export)\s', text, re.M):
        bad = re.search(r'^\s*(import|export)\s.*$', text, re.M).group(0)
        sys.exit(f'{key(path)}: unsupported statement: {bad[:80]}')
    ret = ', '.join(f'{k}: {v}' if k != v else k for k, v in exports.items())
    return f"// ---- {key(path)} ----\n__M[{key(path)!r}] = (function () {{\n{text}\nreturn {{ {ret} }};\n}})();\n"


visit((ROOT / 'js/main.js').resolve())
out = '/* MAX IV Explorer – generated by tools/bundle.py, do not edit. Sources are in js/ */\n(function () {\n"use strict";\nconst __M = {};\n'
out += ''.join(transform(p) for p in order) + '})();\n'
(ROOT / 'game.bundle.js').write_text(out)
print(f'{len(order)} modules -> game.bundle.js ({len(out) // 1024} KB)')
