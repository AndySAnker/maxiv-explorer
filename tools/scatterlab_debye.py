"""Precompute the patterns for the Autonomous-synthesis (ScatterLab) tab with DebyeCalculator -> js/scatterlab_data.js

The game version of ScatterLab (Anker et al., ACS Nano 2026, 20, 6767–6782, doi:10.1021/acsnano.5c15488) needs the
scattering of spherical fcc gold particles of any diameter. This script calculates them on a grid of diameters with
DebyeCalculator (Johansen, Anker et al., J. Open Source Softw. 2024, 9(94), 6024, doi:10.21105/joss.06024), using the
paper's settings for the total-scattering target (F(Q) for Q = 0.5–15 Å⁻¹, B = 0.3 Å²), plus SAXS I(q) for CoSAXS and
both patterns for the unreduced precursor AuCl₄⁻. The game interpolates between the diameters and averages over the
size distribution; G(r) is obtained in the game by Fourier transforming F(Q), like a measured PDF.

    pip install "debyecalculator>=1.1.1"      (grid pair sum, PR #44)
    python3 tools/scatterlab_debye.py
"""
import json, pathlib, sys, time
import numpy as np
from ase import Atoms
from importlib.metadata import version
from debyecalculator import DebyeCalculator

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
from danmax_debye import sphere, AU  # noqa: E402

DIAMETERS = np.round(np.arange(1.5, 10.51, 0.25), 2)  # nm
V5 = 4 / 3 * np.pi * 2.5 ** 3                          # nm³ – SAXS scale: a 5 nm particle has I(q→0)/atom = its volume


def g4(a): return [float(f'{v:.4g}') for v in a]


def main():
    ts = DebyeCalculator(qmin=0.5, qmax=15.04, qstep=0.04, biso=0.3, device='cpu', radiation_type='xray', pair_sum='grid')
    sx = DebyeCalculator(qmin=0.005, qmax=0.555, qstep=0.0025, biso=0.3, device='cpu', radiation_type='xray', pair_sum='grid')
    out = {'meta': {'debyecalculator': version('debyecalculator'), 'pair_sum': 'grid', 'biso': 0.3,
                    'cite': 'Johansen, Anker, Friis-Jensen, Dam, Jensen, Selvan, J. Open Source Softw. 2024, 9(94), 6024, doi:10.21105/joss.06024'},
           'D': [float(d) for d in DIAMETERS], 'natoms': [], 'F': [], 'I': []}
    I5 = None; t0 = time.time()
    for d in DIAMETERS:
        at = sphere(AU, d / 2)
        q, f = ts.fq(at); qs, i = sx.iq(at)
        i = np.asarray(i) / len(at)
        if abs(d - 5.0) < 1e-6: I5 = float(i[0])
        out['natoms'].append(len(at)); out['F'].append(np.asarray(f)); out['I'].append(i)
        print(f'd = {d:5.2f} nm: {len(at):6d} atoms')
    scale = V5 / I5
    out['F'] = [g4(f) for f in out['F']]; out['I'] = [g4(i * scale) for i in out['I']]
    out['qTS'] = [round(float(x), 3) for x in q]; out['qS'] = [round(float(x), 5) for x in qs]
    # unreduced precursor: square-planar AuCl₄⁻ (Au–Cl 2.28 Å)
    a = 2.28; prec = Atoms(['Au', 'Cl', 'Cl', 'Cl', 'Cl'], positions=[(0, 0, 0), (a, 0, 0), (-a, 0, 0), (0, a, 0), (0, -a, 0)])
    _, fp = ts.fq(prec); _, ip = sx.iq(prec)
    out['prec'] = {'F': g4(fp), 'I': g4(np.asarray(ip) / len(prec) * scale)}
    (ROOT / 'js/scatterlab_data.js').write_text('// generated by tools/scatterlab_debye.py with DebyeCalculator (grid pair sum)\nexport const SCATTERLAB = '
                                                + json.dumps(out, ensure_ascii=False) + ';\n')
    print(f'wrote js/scatterlab_data.js ({time.time() - t0:.0f} s)')


if __name__ == '__main__':
    main()
