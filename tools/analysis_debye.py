"""Precompute everything the CoSAXS *Analyse* tab needs, with DebyeCalculator (grid pair sum, PR #44):

* the example literature dataset (Bi-oxido cluster growth, Angew. Chem. Int. Ed. 2021, e202103641 – NOT measured at
  CoSAXS) and I(q) for its six candidate cluster structures, and
* size/shape candidates for the game's own samples (Au, CeO2, ZnO), so measured data can be compared to them.

    python3 tools/analysis_debye.py      -> js/analysis_data.js
"""
import json, pathlib, sys, time
import numpy as np
from ase import Atoms
from debyecalculator import DebyeCalculator

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
from cosaxs_debye import sphere, rod, fluorite_cubic  # noqa: E402
from ase.build import bulk  # noqa: E402

VIEW_MAX = 700  # atoms kept for the 3D viewer


def viewer(atoms, rng):
    pos = atoms.get_positions(); el = atoms.get_chemical_symbols()
    idx = np.arange(len(atoms)) if len(atoms) <= VIEW_MAX else rng.choice(len(atoms), VIEW_MAX, replace=False)
    pos = pos[idx] - pos.mean(axis=0)
    return {'el': [el[i] for i in idx], 'xyz': [round(float(v), 2) for v in pos.ravel()]}


def rg_dmax(atoms):
    p = atoms.get_positions(); c = p - p.mean(axis=0)
    rg = float(np.sqrt((c ** 2).sum(axis=1).mean()))
    sub = p if len(p) < 3000 else p[np.random.default_rng(0).choice(len(p), 3000, replace=False)]
    d = np.sqrt(((sub[:, None, :] - sub[None, :, :]) ** 2).sum(-1)).max()
    return round(rg, 2), round(float(d), 2)


def main():
    rng = np.random.default_rng(1)
    out = {}
    # ---- literature example: Bi-oxido clusters ----
    raw = np.loadtxt(ROOT / 'assets/example_data/Cluster_growth_9_1079background_subtracted.dat')
    calc = DebyeCalculator(qmin=0.02, qmax=3.1, qstep=0.005, biso=0.3, device='cpu', radiation_type='xray', pair_sum='grid')
    structs = []
    for s in json.load(open(ROOT / 'assets/example_data/bi_cluster_structures.json')):
        atoms = Atoms(s['elements'], positions=np.column_stack([s['x'], s['y'], s['z']]))
        q, i = calc.iq(atoms)
        rg, dm = rg_dmax(atoms)
        structs.append({'label': s['label'], 'formula': s['formula'], 'natoms': len(atoms), 'rg': rg, 'dmax': dm,
                        'I': [float(f'{v:.5g}') for v in i]} | viewer(atoms, rng))
    out['bi'] = {
        'title': 'Bi-oxido cluster growth (literature example)',
        'cite': 'Angew. Chem. Int. Ed. 2021, e202103641',
        'doi': 'https://doi.org/10.1002/anie.202103641',
        'via': 'https://github.com/AndySAnker/2026_Applications-of-X-ray-and-Neutron-Scattering-in-Biology-Chemistry-and-Physics/tree/main/saxs_analysis',
        'data': {'q': [round(float(v), 5) for v in raw[:, 0]], 'I': [float(f'{v:.5g}') for v in raw[:, 1]]},
        'mq': [round(float(v), 4) for v in q], 'structures': structs,
    }
    print('Bi clusters done:', [(s['label'], s['natoms']) for s in structs])

    # ---- size / shape candidates for the CoSAXS samples ----
    calc2 = DebyeCalculator(qmin=0.002, qmax=3.6, qstep=0.002, biso=0.5, device='cpu', radiation_type='xray', pair_sum='grid')
    au, ceo2, zno = bulk('Au', 'fcc', a=4.078, cubic=True), fluorite_cubic(5.411), bulk('ZnO', 'wurtzite', a=3.250, c=5.207)
    cands = {
        'au': [(f'Au sphere d = {d} nm', lambda d=d: sphere(au, d / 2)) for d in (3, 4, 5, 6, 7)],
        'ceo2': [(f'CeO₂ sphere d = {d} nm', lambda d=d: sphere(ceo2, d / 2)) for d in (4, 5, 6, 7, 8)],
        'zno': [('ZnO sphere d = 3 nm', lambda: sphere(zno, 1.5)), ('ZnO sphere d = 6 nm', lambda: sphere(zno, 3.0)),
                ('ZnO rod 3 × 5 nm', lambda: rod(zno, 1.5, 5)), ('ZnO rod 3 × 9 nm', lambda: rod(zno, 1.5, 9)), ('ZnO rod 3 × 14 nm', lambda: rod(zno, 1.5, 14))],
    }
    # log-spaced q grid for the candidate curves (keeps the file small)
    qlog = np.unique(np.round(np.geomspace(0.002, 3.6, 420), 5))
    out['cand_q'] = [float(v) for v in qlog]
    out['cand'] = {}
    for key, lst in cands.items():
        res = []
        for label, make in lst:
            t0 = time.time(); atoms = make(); q, i = calc2.iq(atoms)
            rg, dm = rg_dmax(atoms)
            res.append({'label': label, 'natoms': len(atoms), 'rg': rg, 'dmax': dm, 'I': [float(f'{v:.5g}') for v in np.interp(qlog, q, i)]} | viewer(atoms, rng))
            print(f'  {label}: {len(atoms)} atoms, {time.time() - t0:.1f} s')
        out['cand'][key] = res
    (ROOT / 'js/analysis_data.js').write_text('// generated by tools/analysis_debye.py with DebyeCalculator (grid pair sum)\nexport const ANALYSIS = ' + json.dumps(out, ensure_ascii=False) + ';\n')
    print('wrote js/analysis_data.js')


if __name__ == '__main__':
    main()
