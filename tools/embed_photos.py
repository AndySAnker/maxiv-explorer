"""Embed down-scaled photos as data URLs so textures also work when index.html is opened from disk (file://)."""
import base64, io, json, pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
out = {}
for p in sorted((root / 'assets/photos').glob('*.jpg')):
    im = Image.open(p).convert('RGB')
    im.thumbnail((1024, 1024))
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=78, optimize=True)
    out[p.name] = 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()
(root / 'js/photodata.js').write_text('// generated by tools/embed_photos.py\nexport const PHOTO_DATA = ' + json.dumps(out) + ';\n')
print(len(out), 'photos,', sum(len(v) for v in out.values()) // 1024, 'KB embedded')
